import { DatePipe } from '@angular/common';
import { Component, OnInit, inject, signal } from '@angular/core';
import { ActivatedRoute, RouterLink } from '@angular/router';
import { AuthService } from '../auth/auth.service';
import { confidenceText } from '../jobs/job-model';
import { resourceError } from '../resource-errors';
import {
  AIAssessment, AIStatus, DISCLAIMER, Match, coveragePercent, factorLabels, factorStatusText, scoreText,
} from './match-model';
import { MatchService } from './match.service';

@Component({
  selector: 'app-match-detail', imports: [DatePipe, RouterLink],
  template: `
    <section class="resource-panel">
      @if (error()) { <h1>Match</h1><p role="alert">{{ error() }}</p> }
      @if (loading() && !match()) { <p role="status">Loading match…</p> }
      @if (match(); as current) {
        <h1>{{ current.job.title }}</h1>
        <p>{{ current.job.company_name ?? 'Unnamed company' }} · <a [routerLink]="['/jobs', current.job.id]">View job details</a></p>
        <p><span class="status-pill score-pill">{{ scoreText(current) }}</span>
          <span class="status-pill">{{ coveragePercent(current.coverage) }}% of your weighting evaluated</span></p>
        <p class="disclaimer">{{ disclaimer }}</p>
        @for (exclusion of current.explanation.exclusions; track exclusion.code) { <p role="note"><strong>Excluded:</strong> {{ exclusion.text }}</p> }
        @for (flag of current.explanation.flags; track flag.code) { <p role="note">{{ flag.text }}</p> }
        <h2>How this was scored</h2>
        <table class="factor-table">
          <thead><tr><th scope="col">Factor</th><th scope="col">Weight</th><th scope="col">Result</th><th scope="col">Points</th></tr></thead>
          <tbody>
            @for (factor of current.explanation.factors; track factor.factor) {
              <tr>
                <th scope="row">{{ factorLabels[factor.factor] }}</th><td>{{ factor.weight }}</td>
                <td>{{ factorStatusText[factor.status] }}<br /><span class="factor-text">{{ factor.text }}</span></td>
                <td>{{ factor.contribution ?? '—' }}</td>
              </tr>
            }
          </tbody>
        </table>
        <p>Job details came from: {{ confidenceText[current.job.confidence] }} Algorithm {{ current.algorithm_version }},
          calculated {{ current.computed_at | date:'medium' }}.</p>
        @if (aiStatus()?.enabled && canUseAI()) {
          <h2>AI assessment (advisory)</h2>
          <p class="disclaimer">Asking AI sends this job's text and this profile's criteria to the configured AI service (OpenRouter).
            No account details are sent. The AI cannot change the score above.</p>
          @if (assessment(); as ai) {
            <p class="job-text">{{ ai.result.summary }}</p>
            @if (ai.result.requirements.length) { <h3>Requirements the AI found</h3><ul>@for (item of ai.result.requirements; track $index) { <li>{{ item }}</li> }</ul> }
            @if (ai.result.notes.length) { <h3>Not stated in the posting</h3><ul>@for (item of ai.result.notes; track $index) { <li>{{ item }}</li> }</ul> }
            <p>Generated by {{ ai.model }} on {{ ai.created_at | date:'medium' }}.</p>
          } @else {
            <button type="button" (click)="askAI()" [disabled]="asking() || (aiStatus()?.remaining_today ?? 0) === 0">Ask AI</button>
            <p>{{ aiStatus()?.remaining_today ?? 0 }} AI requests left today.</p>
          }
          @if (aiMessage()) { <p role="status">{{ aiMessage() }}</p> }
        }
      }
      <div class="actions"><a [routerLink]="['/preferences', profileId, 'matches']">Back to matches</a></div>
    </section>
  `,
})
export class MatchDetail implements OnInit {
  private readonly api = inject(MatchService); private readonly auth = inject(AuthService);
  private readonly route = inject(ActivatedRoute);
  readonly profileId = this.route.snapshot.paramMap.get('id') ?? '';
  readonly disclaimer = DISCLAIMER; readonly factorLabels = factorLabels; readonly factorStatusText = factorStatusText;
  readonly confidenceText = confidenceText; readonly scoreText = scoreText; readonly coveragePercent = coveragePercent;
  readonly match = signal<Match | null>(null); readonly assessment = signal<AIAssessment | null>(null);
  readonly aiStatus = signal<AIStatus | null>(null); readonly aiMessage = signal('');
  readonly loading = signal(false); readonly asking = signal(false); readonly error = signal('');
  canUseAI(): boolean { return this.auth.user()?.permissions.includes('ai:use:self') ?? false; }
  ngOnInit(): void {
    void this.load(this.route.snapshot.paramMap.get('jobId') ?? '');
    if (this.canUseAI()) void this.api.aiStatus().then(status => this.aiStatus.set(status), () => undefined);
  }
  async load(jobId: string): Promise<void> {
    this.loading.set(true); this.error.set('');
    try { const match = await this.api.get(this.profileId, jobId); this.match.set(match); this.assessment.set(match.ai_assessment); }
    catch (error) { this.error.set(resourceError(error)); }
    finally { this.loading.set(false); }
  }
  async askAI(): Promise<void> {
    const current = this.match(); if (!current || this.asking()) return;
    this.asking.set(true); this.aiMessage.set('');
    try {
      const response = await this.api.assess(this.profileId, current.job.id);
      this.assessment.set(response.assessment);
      if (!response.assessment) this.aiMessage.set(response.message);
      const status = this.aiStatus(); if (status) this.aiStatus.set({ ...status, remaining_today: response.remaining_today });
    } catch (error) { this.aiMessage.set(resourceError(error)); }
    finally { this.asking.set(false); }
  }
}
